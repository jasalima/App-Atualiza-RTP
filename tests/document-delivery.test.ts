import { beforeEach, describe, expect, it, vi } from 'vitest';
const mocks = vi.hoisted(() => ({ load: vi.fn(), query: Object.assign(vi.fn(), {transaction:vi.fn()}), own:vi.fn(), state:vi.fn(), send:vi.fn(), makeFile:vi.fn(), access:vi.fn() }));
vi.mock('../lib/db',()=>({sql:mocks.query}));
vi.mock('../lib/authorize',()=>({requireProject:mocks.access}));
vi.mock('../lib/travel',()=>({sameOrigin:()=>{},travelError:(error:{status?:number;message?:string})=>Response.json({error:error.message},{status:error.status||500})}));
vi.mock('../lib/whatsapp-connections',()=>({ownWhatsApp:mocks.own}));
vi.mock('../lib/connectivity-config',()=>({evolutionForProject:async()=>({state:mocks.state,sendDocument:mocks.send})}));
vi.mock('../lib/document-source',async()=>{
  const {z}=await import('zod');
  return {MAX_DOCUMENT_BYTES:20*1024*1024,loadDocumentSource:mocks.load,recipientNumber:(value:string)=>value.replace(/\D/g,''),documentRequest:z.object({projectId:z.string().uuid(),sourceId:z.string().uuid(),kind:z.enum(['rtp','travel','document']),format:z.enum(['pdf','docx','original'])})};
});
import { POST } from '../app/api/documents/send/route';
import { GET as history } from '../app/api/documents/history/route';
const projectId='10ab6e37-f57e-41e0-8218-6f69d51c33c4';
const sourceId='8a539a45-bf0f-4c9b-9bed-fcbb7ef6d2b1';
const requestId='f18f1394-173c-4f8c-b4ee-84b17d654d38';
const request=(kind='rtp',format='pdf')=>new Request('https://app.example/api/documents/send',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({projectId,sourceId,kind,format,recipientPhone:'5563999999999',requestId,userId:'forged-user',instance:'other-app',media:'https://untrusted.example/file'})});
beforeEach(()=>{
  Object.values(mocks).forEach(fn=>fn.mockReset()); mocks.query.transaction.mockReset();
  mocks.load.mockResolvedValue({session:{user:{id:'current-user'}},version:3,label:'RTP 01/2026',makeFile:mocks.makeFile});
  mocks.makeFile.mockResolvedValue({buffer:Buffer.from('file'),filename:'RTP.pdf',mime:'application/pdf'});
  mocks.own.mockResolvedValue({instance:'Gesproject-current',token:'scoped-key'});mocks.state.mockResolvedValue('open');
  mocks.query.mockResolvedValue([{id:'delivery-id'}]);mocks.query.transaction.mockResolvedValue([]);
  mocks.send.mockResolvedValue({messageId:'provider-id'});
});
describe('shared document sending',()=>{
  it('uses only the authenticated user instance and the file generated by the server',async()=>{
    const response=await POST(request());expect(response.status).toBe(200);
    expect(mocks.own).toHaveBeenCalledWith(projectId,'current-user');
    expect(mocks.send).toHaveBeenCalledWith('Gesproject-current','scoped-key',{buffer:Buffer.from('file'),filename:'RTP.pdf',mime:'application/pdf'},'5563999999999','RTP 01/2026. Documento do projeto.');
    expect(mocks.load.mock.calls[0][0]).not.toHaveProperty('media');
    expect(mocks.query.transaction).toHaveBeenCalledTimes(1);
  });
  it.each([['travel','docx'],['document','original']])('shares %s sources through the same route',async(kind,format)=>{
    expect((await POST(request(kind,format))).status).toBe(200);
    expect(mocks.load.mock.calls[0][0]).toMatchObject({kind,format,projectId,sourceId});
  });
  it('rejects unauthorized sources before accessing a connection or provider',async()=>{
    mocks.load.mockRejectedValue({status:403,message:'Acesso negado'});
    expect((await POST(request())).status).toBe(403);expect(mocks.own).not.toHaveBeenCalled();expect(mocks.send).not.toHaveBeenCalled();
  });
  it('requires pairing and never claims a delivery when WhatsApp is offline',async()=>{
    mocks.state.mockResolvedValue('close');
    expect((await POST(request())).status).toBe(409);expect(mocks.query).not.toHaveBeenCalled();expect(mocks.send).not.toHaveBeenCalled();
  });
  it('does not send a duplicate when the atomic rate/idempotency claim is refused',async()=>{
    mocks.query.mockResolvedValue([]);
    expect((await POST(request())).status).toBe(409);expect(mocks.send).not.toHaveBeenCalled();
    expect(mocks.query.mock.calls[0][0].join('?')).toContain('ON CONFLICT DO NOTHING');
  });
  it('records uncertain results without an automatic provider retry',async()=>{
    mocks.send.mockRejectedValue(new Error('timeout'));
    expect((await POST(request())).status).toBe(502);expect(mocks.send).toHaveBeenCalledTimes(1);
    expect(mocks.query.mock.calls.at(-1)![0].join('?')).toContain("status='uncertain'");
    expect(mocks.query.transaction).not.toHaveBeenCalled();
  });
  it('prevents oversized generated files from reaching the provider',async()=>{
    mocks.makeFile.mockResolvedValue({buffer:Buffer.alloc(20*1024*1024+1),filename:'big.pdf',mime:'application/pdf'});
    expect((await POST(request())).status).toBe(413);expect(mocks.send).not.toHaveBeenCalled();
  });
  it('scopes history to the current user/project and masks recipient numbers',async()=>{
    mocks.access.mockResolvedValue({user:{id:'current-user'}});mocks.query.mockResolvedValue([]);
    expect((await history(new Request(`https://app.example/api/documents/history?projectId=${projectId}`))).status).toBe(200);
    const [strings,...values]=mocks.query.mock.calls[0];expect(values).toEqual([projectId,'current-user']);expect(strings.join('?')).toContain('right(recipient_phone,4)');
  });
});
